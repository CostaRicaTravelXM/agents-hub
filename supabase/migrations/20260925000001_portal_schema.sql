-- ---------------------------------------------------------------- catalogue
create table public.packages (
  id bigint generated by default as identity primary key,
  name text not null,
  destination text not null,
  description text not null,
  trip_types public.trip_type[] not null default '{}',
  settings public.destination_setting[] not null default '{}',
  price_per_person numeric(10, 2) not null check (price_per_person >= 0),
  duration_days int not null check (duration_days > 0),
  commission_rate numeric(5, 2) not null check (commission_rate between 0 and 100),
  rating numeric(2, 1) not null default 0 check (rating between 0 and 5),
  review_count int not null default 0,
  image_url text not null,
  gallery text[] not null default '{}',
  highlights text[] not null default '{}',
  -- [{ "day": 1, "title": "…", "description": "…" }]
  itinerary jsonb not null default '[]',
  inclusions text[] not null default '{}',
  what_to_bring text[] not null default '{}',
  kid_friendly boolean not null default false,
  min_age int,
  -- Featured packages are chosen by TravelXM staff, never by agents.
  is_featured boolean not null default false,
  featured_rank int,
  is_active boolean not null default true,
  embedding extensions.vector(1536),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index packages_featured_idx on public.packages (is_featured, featured_rank) where is_active;
create index packages_trip_types_idx on public.packages using gin (trip_types);
create index packages_settings_idx on public.packages using gin (settings);
create trigger packages_touch before update on public.packages
  for each row execute function public.touch_updated_at();

