-- TravelXM Agent Portal · schema
-- The Agent Portal (agents.travelxm.com) and the Academy share this database
-- and its users: portal agents are the same auth.users / public.profiles rows
-- the Academy uses. Portal tables are additive and never alter Academy tables.
-- Access control lives in 20260925000002_portal_access.sql, dashboard
-- aggregates and demo data in 20260925000003_portal_functions.sql.

-- pgvector: semantic package/support search lands on these columns later.
create extension if not exists vector with schema extensions;

