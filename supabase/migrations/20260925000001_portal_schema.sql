-- ---------------------------------------------------------------- bookkeeping
-- Every booking carries exactly one commission row, priced from its snapshot rate.
create or replace function public.portal_booking_commission()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if tg_op = 'INSERT' then
    insert into public.commissions (agent_id, booking_id, amount, status, earned_at)
    values (new.agent_id, new.id, round(new.total_amount * new.commission_rate / 100, 2), 'pending', new.booked_at::date);
  elsif new.total_amount is distinct from old.total_amount or new.commission_rate is distinct from old.commission_rate then
    update public.commissions
       set amount = round(new.total_amount * new.commission_rate / 100, 2)
     where booking_id = new.id;
  end if;
  return new;
end $$;
create trigger bookings_commission after insert or update on public.bookings
  for each row execute function public.portal_booking_commission();

-- Booking activity feeds the dashboard's "Recent activity".
create or replace function public.portal_booking_activity()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  v_customer text;
  v_package text;
begin
  select c.first_name || ' ' || c.last_name into v_customer from public.customers c where c.id = new.customer_id;
  select p.name into v_package from public.packages p where p.id = new.package_id;
  if tg_op = 'INSERT' then
    insert into public.activity_events (agent_id, description, customer_name, amount, created_at)
    values (new.agent_id, 'New booking created for ' || v_package, v_customer, new.total_amount, new.booked_at);
  elsif new.status is distinct from old.status then
    insert into public.activity_events (agent_id, description, customer_name)
    values (new.agent_id, 'Booking #' || new.id || ' marked ' || new.status::text, v_customer);
  end if;
  return new;
end $$;
create trigger bookings_activity after insert or update of status on public.bookings
  for each row execute function public.portal_booking_activity();

-- Per-customer totals, computed rather than stored so they never drift.
create view public.customer_stats with (security_invoker = true) as
select
  c.*,
  count(b.id) filter (where b.status <> 'cancelled')::int as total_bookings,
  coalesce(sum(b.total_amount) filter (where b.status <> 'cancelled'), 0)::numeric(12, 2) as total_spent
from public.customers c
left join public.bookings b on b.customer_id = c.id
group by c.id;

-- Bookings joined with the names the tables show.
create view public.booking_details with (security_invoker = true) as
select
  b.*,
  c.first_name || ' ' || c.last_name as customer_name,
  c.email as customer_email,
  p.name as package_name,
  p.destination
from public.bookings b
join public.customers c on c.id = b.customer_id
join public.packages p on p.id = b.package_id;
