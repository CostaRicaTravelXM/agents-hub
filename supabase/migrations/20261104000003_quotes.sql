-- Direct inserts run as `authenticated`. The functions below run as another role and
-- keep what they set, the same way portal_price_booking does.
create or replace function public.quote_prepare_request()
returns trigger language plpgsql set search_path = public as $$
begin
  if current_user = 'authenticated' then
    new.agent_id := auth.uid();
    new.status := 'requested';
    new.created_at := now();
    new.updated_at := now();
  end if;
  return new;
end $$;
create trigger quote_requests_prepare before insert on public.quote_requests
  for each row execute function public.quote_prepare_request();

create or replace function public.quote_request_created()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  perform public.quote_notify_staff('New quote request', new.destination || ', ' || new.travelers || ' travelers.', new.id);
  return new;
end $$;
create trigger quote_requests_created after insert on public.quote_requests
  for each row execute function public.quote_request_created();

create or replace function public.quote_prepare_message()
returns trigger language plpgsql set search_path = public as $$
begin
  if current_user = 'authenticated' then
    new.sender_id := auth.uid();
    new.from_staff := public.is_staff();
    new.kind := 'message';
    new.created_at := now();
  end if;
  return new;
end $$;
create trigger quote_messages_prepare before insert on public.quote_messages
  for each row execute function public.quote_prepare_message();

create or replace function public.quote_message_created()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  v_quote public.quote_requests;
begin
  update public.quote_requests set updated_at = now() where id = new.quote_id returning * into v_quote;
  if new.kind = 'message' then
    if new.from_staff then
      perform public.quote_notify_agent(v_quote.agent_id, 'New message from TravelXM', left(new.body, 140), new.quote_id);
    else
      perform public.quote_notify_staff('New message on quote #' || new.quote_id, left(new.body, 140), new.quote_id);
    end if;
  end if;
  return new;
end $$;
create trigger quote_messages_created after insert on public.quote_messages
  for each row execute function public.quote_message_created();

