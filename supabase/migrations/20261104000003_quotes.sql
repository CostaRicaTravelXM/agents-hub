-- Quotes: an agent asks, TravelXM answers with a weekly itinerary, and accepting it
-- creates the booking. Money and status only change through the functions below.

create type public.catalog_kind as enum ('tour', 'hotel', 'transport');
create type public.quote_status as enum ('requested', 'proposal_sent', 'changes_requested', 'accepted', 'cancelled');
create type public.itinerary_status as enum ('draft', 'published', 'superseded');

-- ---------------------------------------------------------------- tables
create table public.catalog_items (
  id bigint generated by default as identity primary key,
  kind public.catalog_kind not null,
  name text not null,
  location text,
  description text,
  image_url text,
  highlights text[] not null default '{}',
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create trigger catalog_items_touch before update on public.catalog_items
  for each row execute function public.touch_updated_at();

create table public.quote_requests (
  id bigint generated by default as identity (start with 2000) primary key,
  agent_id uuid not null default auth.uid() references public.profiles (id) on delete cascade,
  customer_id bigint not null references public.customers (id) on delete restrict,
  package_id bigint references public.packages (id) on delete set null,
  destination text not null check (char_length(destination) between 1 and 200),
  start_date date not null,
  end_date date not null,
  travelers int not null check (travelers between 1 and 50),
  budget numeric(12, 2) check (budget >= 0),
  notes text check (char_length(notes) <= 4000),
  status public.quote_status not null default 'requested',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (end_date >= start_date)
);
create index quote_requests_agent_idx on public.quote_requests (agent_id, updated_at desc);
create index quote_requests_status_idx on public.quote_requests (status, updated_at desc);
create trigger quote_requests_touch before update on public.quote_requests
  for each row execute function public.touch_updated_at();

create table public.quote_messages (
  id bigint generated by default as identity primary key,
  quote_id bigint not null references public.quote_requests (id) on delete cascade,
  sender_id uuid references public.profiles (id) on delete set null,
  from_staff boolean not null default false,
  -- 'event' lines are written by the functions below ("TravelXM sent version 2").
  kind text not null default 'message' check (kind in ('message', 'event')),
  body text not null check (char_length(body) between 1 and 4000),
  created_at timestamptz not null default now()
);
create index quote_messages_quote_idx on public.quote_messages (quote_id, created_at);

create table public.itinerary_versions (
  id bigint generated by default as identity primary key,
  quote_id bigint not null references public.quote_requests (id) on delete cascade,
  version int not null,
  status public.itinerary_status not null default 'draft',
  summary text check (char_length(summary) <= 4000),
  total_price numeric(12, 2) check (total_price >= 0),
  commission_rate numeric(5, 2) check (commission_rate between 0 and 100),
  valid_until date,
  published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (quote_id, version)
);
create unique index itinerary_versions_one_draft on public.itinerary_versions (quote_id) where status = 'draft';
create unique index itinerary_versions_one_published on public.itinerary_versions (quote_id) where status = 'published';
create trigger itinerary_versions_touch before update on public.itinerary_versions
  for each row execute function public.touch_updated_at();

-- Items copy the catalogue's text and photo, so editing the catalogue never changes
-- a proposal already sent. Times are the trip's local time, with no time zone, so
-- they read the same from any country.
create table public.itinerary_items (
  id bigint generated by default as identity primary key,
  version_id bigint not null references public.itinerary_versions (id) on delete cascade,
  kind public.catalog_kind not null,
  catalog_item_id bigint references public.catalog_items (id) on delete set null,
  title text not null check (char_length(title) between 1 and 200),
  location text,
  description text,
  image_url text,
  highlights text[] not null default '{}',
  start_at timestamp not null,
  end_at timestamp not null,
  created_at timestamptz not null default now(),
  check (end_at >= start_at)
);
create index itinerary_items_version_idx on public.itinerary_items (version_id, start_at);

-- One live link per quote. It always shows the latest published version. Only the
-- hash is stored, so a database read never reveals a working link.
create table public.quote_share_links (
  quote_id bigint primary key references public.quote_requests (id) on delete cascade,
  token_hash text not null unique,
  show_price boolean not null default false,
  created_at timestamptz not null default now(),
  revoked_at timestamptz
);

