  for select to authenticated using (exists (select 1 from public.itinerary_versions v where v.id = version_id));
create policy itinerary_items_write on public.itinerary_items
  for all to authenticated
  using (public.is_staff() and exists (select 1 from public.itinerary_versions v where v.id = version_id and v.status = 'draft'))
  with check (public.is_staff() and exists (select 1 from public.itinerary_versions v where v.id = version_id and v.status = 'draft'));

