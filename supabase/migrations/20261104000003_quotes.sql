  for select to authenticated using (
    public.is_staff()
    or (status <> 'draft' and exists (select 1 from public.quote_requests q where q.id = quote_id))
  );
create policy itinerary_versions_update on public.itinerary_versions
  for update to authenticated using (public.is_staff() and status = 'draft') with check (public.is_staff() and status = 'draft');

