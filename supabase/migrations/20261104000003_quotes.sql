  for select to authenticated using (exists (select 1 from public.quote_requests q where q.id = quote_id));
create policy quote_messages_insert on public.quote_messages
  for insert to authenticated with check (
    sender_id = auth.uid()
    and exists (select 1 from public.quote_requests q where q.id = quote_id and q.status <> 'cancelled')
  );

-- Agents never see a draft.
