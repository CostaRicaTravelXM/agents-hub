-- ---------------------------------------------------------------- team
-- Opens the quote's draft, starting from the last version sent when there is one.
create or replace function public.quote_start_draft(p_quote_id bigint)
returns bigint language plpgsql security definer set search_path = public as $$
declare
  v_quote public.quote_requests;
  v_last public.itinerary_versions;
  v_id bigint;
begin
  if not public.is_staff() then raise exception 'staff only' using errcode = '42501'; end if;
  select * into v_quote from public.quote_requests where id = p_quote_id for update;
  if not found then raise exception 'that quote does not exist' using errcode = 'P0001'; end if;
  if v_quote.status in ('accepted', 'cancelled') then
    raise exception 'this quote is closed' using errcode = 'P0001';
  end if;

  select id into v_id from public.itinerary_versions where quote_id = p_quote_id and status = 'draft';
  if found then return v_id; end if;

  select * into v_last from public.itinerary_versions where quote_id = p_quote_id order by version desc limit 1;
  insert into public.itinerary_versions (quote_id, version, summary, total_price, commission_rate, valid_until)
  values (p_quote_id, coalesce(v_last.version, 0) + 1, v_last.summary, v_last.total_price, v_last.commission_rate, v_last.valid_until)
  returning id into v_id;

  if v_last.id is not null then
    insert into public.itinerary_items (version_id, kind, catalog_item_id, title, location, description, image_url, highlights, start_at, end_at)
    select v_id, kind, catalog_item_id, title, location, description, image_url, highlights, start_at, end_at
    from public.itinerary_items where version_id = v_last.id;
  end if;
  return v_id;
end $$;

create or replace function public.quote_publish_version(p_version_id bigint)
returns void language plpgsql security definer set search_path = public as $$
declare
  v_version public.itinerary_versions;
  v_quote public.quote_requests;
begin
  if not public.is_staff() then raise exception 'staff only' using errcode = '42501'; end if;
  select * into v_version from public.itinerary_versions where id = p_version_id and status = 'draft' for update;
  if not found then raise exception 'that draft does not exist' using errcode = 'P0001'; end if;
  select * into v_quote from public.quote_requests where id = v_version.quote_id for update;
  if v_quote.status in ('accepted', 'cancelled') then
    raise exception 'this quote is closed' using errcode = 'P0001';
  end if;
  if not exists (select 1 from public.itinerary_items where version_id = p_version_id) then
    raise exception 'add at least one item to the itinerary' using errcode = 'P0001';
  end if;
  if coalesce(v_version.total_price, 0) <= 0 or v_version.commission_rate is null then
    raise exception 'set the total price and the commission rate' using errcode = 'P0001';
  end if;

  update public.itinerary_versions set status = 'superseded'
   where quote_id = v_version.quote_id and status = 'published';
  update public.itinerary_versions set status = 'published', published_at = now() where id = p_version_id;
  update public.quote_requests set status = 'proposal_sent' where id = v_version.quote_id;

  insert into public.quote_messages (quote_id, sender_id, from_staff, kind, body)
  values (v_version.quote_id, auth.uid(), true, 'event', 'TravelXM sent version ' || v_version.version || ' of the itinerary.');
  perform public.quote_notify_agent(v_quote.agent_id, 'Your itinerary is ready', v_quote.destination || ': version ' || v_version.version || ' is ready to review.', v_quote.id);
end $$;

-- ---------------------------------------------------------------- agent
create or replace function public.quote_request_changes(p_quote_id bigint, p_message text)
returns void language plpgsql security definer set search_path = public as $$
declare
  v_quote public.quote_requests;
begin
  if not public.is_verified_agent() then raise exception 'agent is not verified' using errcode = '42501'; end if;
  select * into v_quote from public.quote_requests where id = p_quote_id and agent_id = auth.uid() for update;
  if not found then raise exception 'that quote does not exist' using errcode = 'P0001'; end if;
  if v_quote.status <> 'proposal_sent' then
    raise exception 'there is no itinerary waiting for your review' using errcode = 'P0001';
  end if;
  if coalesce(trim(p_message), '') = '' then
    raise exception 'tell us what to change' using errcode = 'P0001';
  end if;

  update public.quote_requests set status = 'changes_requested' where id = p_quote_id;
  insert into public.quote_messages (quote_id, sender_id, from_staff, kind, body)
  values (p_quote_id, auth.uid(), false, 'event', 'The agent asked for changes.'),
         (p_quote_id, auth.uid(), false, 'message', trim(p_message));
end $$;

-- Names the version the agent was looking at, so a newer one is never accepted by accident.
create or replace function public.quote_accept(p_version_id bigint)
returns bigint language plpgsql security definer set search_path = public as $$
declare
  v_version public.itinerary_versions;
  v_quote public.quote_requests;
  v_start date;
  v_end date;
  v_booking bigint;
begin
  if not public.is_verified_agent() then raise exception 'agent is not verified' using errcode = '42501'; end if;
  select * into v_version from public.itinerary_versions where id = p_version_id and status = 'published';
  if not found then raise exception 'this itinerary is no longer the latest version' using errcode = 'P0001'; end if;
  select * into v_quote from public.quote_requests where id = v_version.quote_id and agent_id = auth.uid() for update;
  if not found then raise exception 'this itinerary is no longer the latest version' using errcode = 'P0001'; end if;
  if v_quote.status <> 'proposal_sent' then
    raise exception 'there is no itinerary waiting for your review' using errcode = 'P0001';
  end if;
  if v_version.valid_until is not null and v_version.valid_until < current_date then
    raise exception 'this proposal has expired, so ask TravelXM to renew it' using errcode = 'P0001';
  end if;

  select min(start_at)::date, max(end_at)::date into v_start, v_end
  from public.itinerary_items where version_id = p_version_id;

  insert into public.bookings (agent_id, customer_id, quote_id, start_date, end_date, travelers, total_amount, commission_rate, status)
  values (v_quote.agent_id, v_quote.customer_id, v_quote.id, v_start, v_end, v_quote.travelers, v_version.total_price, v_version.commission_rate, 'pending')
  returning id into v_booking;

  update public.quote_requests set status = 'accepted' where id = v_quote.id;
  insert into public.quote_messages (quote_id, sender_id, from_staff, kind, body)
  values (v_quote.id, auth.uid(), false, 'event', 'The agent accepted version ' || v_version.version || '. Booking #' || v_booking || ' was created.');
  perform public.quote_notify_staff('Quote #' || v_quote.id || ' accepted', 'Booking #' || v_booking || ' was created for ' || v_quote.destination || '.', v_quote.id);
  return v_booking;
end $$;

create or replace function public.quote_cancel(p_quote_id bigint)
returns void language plpgsql security definer set search_path = public as $$
declare
  v_quote public.quote_requests;
  v_staff boolean := public.is_staff();
begin
  select * into v_quote from public.quote_requests
   where id = p_quote_id and (v_staff or (agent_id = auth.uid() and public.is_verified_agent())) for update;
  if not found then raise exception 'that quote does not exist' using errcode = 'P0001'; end if;
  if v_quote.status in ('accepted', 'cancelled') then
    raise exception 'this quote is closed' using errcode = 'P0001';
  end if;

  update public.quote_requests set status = 'cancelled' where id = p_quote_id;
  update public.quote_share_links set revoked_at = now() where quote_id = p_quote_id and revoked_at is null;
  insert into public.quote_messages (quote_id, sender_id, from_staff, kind, body)
  values (p_quote_id, auth.uid(), v_staff, 'event', 'This quote was cancelled.');
  if v_staff then
    perform public.quote_notify_agent(v_quote.agent_id, 'Quote cancelled', v_quote.destination || ' was cancelled by TravelXM.', v_quote.id);
  else
    perform public.quote_notify_staff('Quote #' || v_quote.id || ' cancelled', v_quote.destination || ' was cancelled by the agent.', v_quote.id);
  end if;
end $$;

-- ---------------------------------------------------------------- client link
-- Returns the only copy of the token. A new link replaces the old one.
create or replace function public.quote_share_create(p_quote_id bigint, p_show_price boolean)
returns text language plpgsql security definer set search_path = public as $$
declare
  v_token text := encode(extensions.gen_random_bytes(32), 'hex');
begin
  if not public.is_verified_agent() then raise exception 'agent is not verified' using errcode = '42501'; end if;
  if not exists (
    select 1 from public.quote_requests q
    join public.itinerary_versions v on v.quote_id = q.id and v.status = 'published'
    where q.id = p_quote_id and q.agent_id = auth.uid() and q.status <> 'cancelled'
  ) then
    raise exception 'there is no itinerary to share yet' using errcode = 'P0001';
  end if;

  insert into public.quote_share_links (quote_id, token_hash, show_price)
  values (p_quote_id, encode(sha256(convert_to(v_token, 'UTF8')), 'hex'), p_show_price)
  on conflict (quote_id) do update
    set token_hash = excluded.token_hash, show_price = excluded.show_price, created_at = now(), revoked_at = null;
  return v_token;
end $$;

create or replace function public.quote_share_update(p_quote_id bigint, p_show_price boolean, p_revoke boolean)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.is_verified_agent() then raise exception 'agent is not verified' using errcode = '42501'; end if;
  update public.quote_share_links l
     set show_price = p_show_price,
         revoked_at = case when p_revoke then coalesce(l.revoked_at, now()) else l.revoked_at end
   where l.quote_id = p_quote_id
     and exists (select 1 from public.quote_requests q where q.id = p_quote_id and q.agent_id = auth.uid());
end $$;

-- What the client sees, without an account. Never includes commission, notes or budget.
create or replace function public.get_shared_trip(p_token text)
returns jsonb language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'destination', q.destination,
    'travelers', q.travelers,
    'summary', v.summary,
    'price', case when l.show_price then v.total_price end,
    'preparedBy', p.full_name,
    'company', p.company,
    'items', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', i.id, 'kind', i.kind, 'title', i.title, 'location', i.location,
        'description', i.description, 'imageUrl', i.image_url, 'highlights', i.highlights,
        'startAt', i.start_at, 'endAt', i.end_at
      ) order by i.start_at, i.id)
      from public.itinerary_items i where i.version_id = v.id
    ), '[]'::jsonb)
  )
  from public.quote_share_links l
  join public.quote_requests q on q.id = l.quote_id and q.status <> 'cancelled'
  join public.itinerary_versions v on v.quote_id = q.id and v.status = 'published'
  join public.profiles p on p.id = q.agent_id
  where l.token_hash = encode(sha256(convert_to(p_token, 'UTF8')), 'hex')
    and l.revoked_at is null;
$$;

