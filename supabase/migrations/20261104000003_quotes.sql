-- Agents still cannot price anything themselves, nor claim a quote directly.
create or replace function public.portal_price_booking()
returns trigger language plpgsql set search_path = public as $$
declare
  v_price numeric;
  v_rate numeric;
  v_days int;
begin
  if current_user <> 'authenticated' then return new; end if;
  if not public.is_verified_agent() then
    raise exception 'agent is not verified' using errcode = '42501';
  end if;

  select p.price_per_person, p.commission_rate, p.duration_days into v_price, v_rate, v_days
  from public.packages p
  where p.id = new.package_id and p.is_active;
  if not found then
    raise exception 'that package is no longer available' using errcode = 'P0001';
  end if;

  new.total_amount := v_price * new.travelers;
  new.commission_rate := v_rate;
  new.end_date := new.start_date + (v_days - 1);
  new.status := 'pending';
  new.booked_at := now();
  new.quote_id := null;
  return new;
end $$;

create or replace function public.portal_booking_activity()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  v_customer text;
  v_trip text;
begin
  select c.first_name || ' ' || c.last_name into v_customer from public.customers c where c.id = new.customer_id;
  select coalesce(
    (select p.name from public.packages p where p.id = new.package_id),
    (select q.destination from public.quote_requests q where q.id = new.quote_id),
    'a custom itinerary'
  ) into v_trip;
  if tg_op = 'INSERT' then
    insert into public.activity_events (agent_id, description, customer_name, amount, created_at)
    values (new.agent_id, 'New booking created for ' || v_trip, v_customer, new.total_amount, new.booked_at);
  elsif new.status is distinct from old.status then
    insert into public.activity_events (agent_id, description, customer_name)
    values (new.agent_id, 'Booking #' || new.id || ' marked ' || new.status::text, v_customer);
  end if;
  return new;
end $$;

drop view public.booking_details;
create view public.booking_details with (security_invoker = true) as
select
  b.*,
  c.first_name || ' ' || c.last_name as customer_name,
  c.email as customer_email,
  coalesce(p.name, 'Custom itinerary') as package_name,
  coalesce(p.destination, q.destination) as destination
from public.bookings b
join public.customers c on c.id = b.customer_id
left join public.packages p on p.id = b.package_id
left join public.quote_requests q on q.id = b.quote_id;
revoke all on public.booking_details from anon;

