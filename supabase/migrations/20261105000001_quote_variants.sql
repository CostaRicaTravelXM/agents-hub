  id bigint generated by default as identity primary key,
  proposal_id bigint not null references public.quote_proposals (id) on delete cascade,
  position int not null default 0,
  -- A draft can be half filled in. Sending checks that every option is complete.
  title text check (char_length(title) <= 200),
  start_date date,
  end_date date,
  summary text check (char_length(summary) <= 4000),
  total_price numeric(12, 2) check (total_price >= 0),
  commission_rate numeric(5, 2) check (commission_rate between 0 and 100),
  valid_until date,
  accepted_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (end_date >= start_date)
);
