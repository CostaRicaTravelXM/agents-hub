-- Names the option the agent was looking at, so a newer round is never accepted by accident.
create function public.quote_accept(p_variant_id bigint)
returns bigint language plpgsql security definer set search_path = public as $$
declare
  v_variant public.quote_variants;
  v_proposal public.quote_proposals;
  v_quote public.quote_requests;
  v_booking bigint;
begin
  if not public.is_verified_agent() then raise exception 'agent is not verified' using errcode = '42501'; end if;
  select * into v_variant from public.quote_variants where id = p_variant_id;
  select * into v_proposal from public.quote_proposals where id = v_variant.proposal_id and status = 'published';
  if not found then raise exception 'this option is no longer part of the latest proposal' using errcode = 'P0001'; end if;
  select * into v_quote from public.quote_requests where id = v_proposal.quote_id and agent_id = auth.uid() for update;
  if not found then raise exception 'this option is no longer part of the latest proposal' using errcode = 'P0001'; end if;
  if v_quote.status <> 'proposal_sent' then
    raise exception 'there is no proposal waiting for your review' using errcode = 'P0001';
  end if;
  if v_variant.valid_until is not null and v_variant.valid_until < current_date then
    raise exception 'this option has expired, so ask TravelXM to renew it' using errcode = 'P0001';
  end if;

  insert into public.bookings (agent_id, customer_id, quote_id, variant_id, start_date, end_date, travelers, total_amount, commission_rate, status)
  values (v_quote.agent_id, v_quote.customer_id, v_quote.id, v_variant.id, v_variant.start_date, v_variant.end_date, v_quote.travelers, v_variant.total_price, v_variant.commission_rate, 'pending')
  returning id into v_booking;

  update public.quote_variants set accepted_at = now() where id = v_variant.id;
  update public.quote_requests set status = 'accepted' where id = v_quote.id;
  insert into public.quote_messages (quote_id, sender_id, from_staff, kind, body)
  values (v_quote.id, auth.uid(), false, 'event', 'The agent accepted ' || v_variant.title || '. Booking #' || v_booking || ' was created.');
  perform public.quote_notify_staff('Quote #' || v_quote.id || ' accepted', v_variant.title || ': booking #' || v_booking || ' was created.', v_quote.id);
  return v_booking;
end $$;

create or replace function public.quote_request_changes(p_quote_id bigint, p_message text)
returns void language plpgsql security definer set search_path = public as $$
declare
  v_quote public.quote_requests;
begin
  if not public.is_verified_agent() then raise exception 'agent is not verified' using errcode = '42501'; end if;
  select * into v_quote from public.quote_requests where id = p_quote_id and agent_id = auth.uid() for update;
  if not found then raise exception 'that quote does not exist' using errcode = 'P0001'; end if;
  if v_quote.status <> 'proposal_sent' then
    raise exception 'there is no proposal waiting for your review' using errcode = 'P0001';
  end if;
  if coalesce(trim(p_message), '') = '' then
    raise exception 'tell us what to change' using errcode = 'P0001';
  end if;

  update public.quote_requests set status = 'changes_requested' where id = p_quote_id;
  insert into public.quote_messages (quote_id, sender_id, from_staff, kind, body)
  values (p_quote_id, auth.uid(), false, 'event', 'The agent asked for changes.'),
         (p_quote_id, auth.uid(), false, 'message', trim(p_message));
end $$;

create or replace function public.quote_cancel(p_quote_id bigint)
returns void language plpgsql security definer set search_path = public as $$
declare
  v_quote public.quote_requests;
  v_staff boolean := public.is_staff();
  v_label text;
begin
  select * into v_quote from public.quote_requests
   where id = p_quote_id and (v_staff or (agent_id = auth.uid() and public.is_verified_agent())) for update;
  if not found then raise exception 'that quote does not exist' using errcode = 'P0001'; end if;
  if v_quote.status in ('accepted', 'cancelled') then
    raise exception 'this quote is closed' using errcode = 'P0001';
  end if;
  v_label := public.quote_label(v_quote.destination, v_quote.id);

  update public.quote_requests set status = 'cancelled' where id = p_quote_id;
  update public.quote_share_links set revoked_at = now() where quote_id = p_quote_id and revoked_at is null;
  insert into public.quote_messages (quote_id, sender_id, from_staff, kind, body)
  values (p_quote_id, auth.uid(), v_staff, 'event', 'This quote was cancelled.');
  if v_staff then
    perform public.quote_notify_agent(v_quote.agent_id, 'Quote cancelled', v_label || ' was cancelled by TravelXM.', v_quote.id);
  else
    perform public.quote_notify_staff('Quote #' || v_quote.id || ' cancelled', v_label || ' was cancelled by the agent.', v_quote.id);
  end if;
end $$;

-- ---------------------------------------------------------------- client link
create or replace function public.quote_share_create(p_quote_id bigint, p_show_price boolean)
returns text language plpgsql security definer set search_path = public as $$
declare
  v_token text := encode(extensions.gen_random_bytes(32), 'hex');
begin
  if not public.is_verified_agent() then raise exception 'agent is not verified' using errcode = '42501'; end if;
  if not exists (
    select 1 from public.quote_requests q
    join public.quote_proposals p on p.quote_id = q.id and p.status = 'published'
    where q.id = p_quote_id and q.agent_id = auth.uid() and q.status <> 'cancelled'
  ) then
    raise exception 'there is no proposal to share yet' using errcode = 'P0001';
  end if;

  insert into public.quote_share_links (quote_id, token_hash, show_price)
  values (p_quote_id, encode(sha256(convert_to(v_token, 'UTF8')), 'hex'), p_show_price)
  on conflict (quote_id) do update
    set token_hash = excluded.token_hash, show_price = excluded.show_price, created_at = now(), revoked_at = null;
  return v_token;
end $$;

-- What the client sees, without an account. Never includes commission, notes or budget.
create or replace function public.get_shared_trip(p_token text)
returns jsonb language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'destination', q.destination,
    'travelers', q.travelers,
    'preparedBy', a.full_name,
    'company', a.company,
    'variants', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', v.id,
        'title', v.title,
        'startDate', v.start_date,
        'endDate', v.end_date,
        'summary', v.summary,
        'price', case when l.show_price then v.total_price end,
        'validUntil', v.valid_until,
        'accepted', v.accepted_at is not null,
        'files', coalesce((
          select jsonb_agg(jsonb_build_object('path', f.path, 'name', f.name, 'contentType', f.content_type) order by f.position, f.id)
          from public.quote_variant_files f where f.variant_id = v.id
        ), '[]'::jsonb)
      ) order by v.position, v.id)
      from public.quote_variants v where v.proposal_id = p.id
    ), '[]'::jsonb)
  )
  from public.quote_share_links l
  join public.quote_requests q on q.id = l.quote_id and q.status <> 'cancelled'
  join public.quote_proposals p on p.quote_id = q.id and p.status = 'published'
  join public.profiles a on a.id = q.agent_id
  where l.token_hash = encode(sha256(convert_to(p_token, 'UTF8')), 'hex')
    and l.revoked_at is null;
$$;

-- ---------------------------------------------------------------- admin
-- Admins can correct anything, on behalf of any agent. Money and status still change
-- only through these functions, and a booking's commission follows its trigger.

create or replace function public.admin_save_quote(p_id bigint, p_fields jsonb)
returns bigint language plpgsql security definer set search_path = public as $$
declare
  v_quote public.quote_requests;
  v_agent uuid;
  v_customer bigint := (p_fields ->> 'customerId')::bigint;
  v_status public.quote_status := coalesce(p_fields ->> 'status', 'requested')::public.quote_status;
  v_id bigint;
begin
  if not public.is_admin() then raise exception 'admins only' using errcode = '42501'; end if;

  if p_id is null then
    v_agent := (p_fields ->> 'agentId')::uuid;
    v_status := 'requested';
  else
    select * into v_quote from public.quote_requests where id = p_id for update;
    if not found then raise exception 'that quote does not exist' using errcode = 'P0001'; end if;
    v_agent := v_quote.agent_id;
    if v_quote.status = 'accepted' and v_status <> 'accepted' then
      raise exception 'this quote has a booking, so delete the booking to reopen it' using errcode = 'P0001';
    end if;
    if v_status = 'accepted' and v_quote.status <> 'accepted' then
      raise exception 'a quote is only accepted when the agent picks an option' using errcode = 'P0001';
    end if;
    if v_status = 'proposal_sent' and not exists (
      select 1 from public.quote_proposals where quote_id = p_id and status = 'published'
    ) then
      raise exception 'send a proposal before marking the quote as sent' using errcode = 'P0001';
    end if;
  end if;

  if not exists (select 1 from public.customers c where c.id = v_customer and c.agent_id = v_agent) then
    raise exception 'that client does not belong to this agent' using errcode = 'P0001';
  end if;

  if p_id is null then
    insert into public.quote_requests (agent_id, customer_id, package_id, destination, start_date, end_date, travelers, budget, notes)
    values (
      v_agent, v_customer, (p_fields ->> 'packageId')::bigint, nullif(trim(p_fields ->> 'destination'), ''),
      (p_fields ->> 'startDate')::date, (p_fields ->> 'endDate')::date, (p_fields ->> 'travelers')::int,
      (p_fields ->> 'budget')::numeric, nullif(trim(p_fields ->> 'notes'), '')
    )
    returning id into v_id;
    perform public.quote_notify_agent(v_agent, 'TravelXM opened a quote for you', 'Quote #' || v_id || ' is in your Quotes.', v_id);
    return v_id;
  end if;

  update public.quote_requests set
    customer_id = v_customer,
    package_id = (p_fields ->> 'packageId')::bigint,
    destination = nullif(trim(p_fields ->> 'destination'), ''),
    start_date = (p_fields ->> 'startDate')::date,
    end_date = (p_fields ->> 'endDate')::date,
    travelers = (p_fields ->> 'travelers')::int,
    budget = (p_fields ->> 'budget')::numeric,
    notes = nullif(trim(p_fields ->> 'notes'), ''),
    status = v_status
  where id = p_id;
  return p_id;
end $$;

create or replace function public.admin_delete_quote(p_id bigint)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'admins only' using errcode = '42501'; end if;
  delete from public.notifications where href in ('/quotes/' || p_id, '/admin/quotes/' || p_id);
  delete from public.quote_requests where id = p_id;
  if not found then raise exception 'that quote does not exist' using errcode = 'P0001'; end if;
end $$;

create or replace function public.admin_save_booking(p_id bigint, p_fields jsonb)
returns bigint language plpgsql security definer set search_path = public as $$
declare
  v_booking public.bookings;
  v_agent uuid;
  v_customer bigint := (p_fields ->> 'customerId')::bigint;
  v_package bigint := (p_fields ->> 'packageId')::bigint;
  v_id bigint;
begin
  if not public.is_admin() then raise exception 'admins only' using errcode = '42501'; end if;

  if p_id is null then
    v_agent := (p_fields ->> 'agentId')::uuid;
    if v_package is null then raise exception 'choose a package' using errcode = 'P0001'; end if;
  else
    select * into v_booking from public.bookings where id = p_id for update;
    if not found then raise exception 'that booking does not exist' using errcode = 'P0001'; end if;
    v_agent := v_booking.agent_id;
    if v_package is null and v_booking.quote_id is null and v_booking.package_id is not null then
      raise exception 'choose a package' using errcode = 'P0001';
    end if;
  end if;

  if not exists (select 1 from public.customers c where c.id = v_customer and c.agent_id = v_agent) then
    raise exception 'that client does not belong to this agent' using errcode = 'P0001';
  end if;

  if p_id is null then
    insert into public.bookings (agent_id, customer_id, package_id, start_date, end_date, travelers, total_amount, commission_rate, status, notes)
    values (
      v_agent, v_customer, v_package,
      (p_fields ->> 'startDate')::date, (p_fields ->> 'endDate')::date, (p_fields ->> 'travelers')::int,
      (p_fields ->> 'totalAmount')::numeric, (p_fields ->> 'commissionRate')::numeric,
      (p_fields ->> 'status')::public.booking_status, nullif(trim(p_fields ->> 'notes'), '')
    )
    returning id into v_id;
    return v_id;
  end if;

  update public.bookings set
    customer_id = v_customer,
    package_id = v_package,
    start_date = (p_fields ->> 'startDate')::date,
    end_date = (p_fields ->> 'endDate')::date,
    travelers = (p_fields ->> 'travelers')::int,
    total_amount = (p_fields ->> 'totalAmount')::numeric,
    commission_rate = (p_fields ->> 'commissionRate')::numeric,
    status = (p_fields ->> 'status')::public.booking_status,
    notes = nullif(trim(p_fields ->> 'notes'), '')
  where id = p_id;
  return p_id;
end $$;

-- A booking from a quote hands the choice back to the agent. Its commission row goes with it.
create or replace function public.admin_delete_booking(p_id bigint)
returns void language plpgsql security definer set search_path = public as $$
declare
  v_booking public.bookings;
begin
  if not public.is_admin() then raise exception 'admins only' using errcode = '42501'; end if;
  select * into v_booking from public.bookings where id = p_id for update;
  if not found then raise exception 'that booking does not exist' using errcode = 'P0001'; end if;

  delete from public.bookings where id = p_id;

  if v_booking.quote_id is not null then
    update public.quote_variants set accepted_at = null where id = v_booking.variant_id;
    update public.quote_requests q
       set status = case
         when exists (select 1 from public.quote_proposals p where p.quote_id = q.id and p.status = 'published') then 'proposal_sent'::public.quote_status
         else 'requested'::public.quote_status
       end
     where q.id = v_booking.quote_id;
    insert into public.quote_messages (quote_id, sender_id, from_staff, kind, body)
    values (v_booking.quote_id, auth.uid(), true, 'event', 'TravelXM removed booking #' || p_id || ', so this quote is open again.');
  end if;
end $$;

