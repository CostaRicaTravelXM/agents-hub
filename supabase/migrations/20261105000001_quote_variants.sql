-- Every earlier proposal becomes a single option with the same money.
insert into public.quote_variants (proposal_id, title, start_date, end_date, summary, total_price, commission_rate, valid_until)
select
  p.id,
  coalesce(q.destination, 'Custom trip'),
  coalesce((select min(i.start_at)::date from public.itinerary_items i where i.version_id = p.id), q.start_date),
  coalesce((select max(i.end_at)::date from public.itinerary_items i where i.version_id = p.id), q.end_date),
  p.summary, p.total_price, p.commission_rate, p.valid_until
from public.quote_proposals p
join public.quote_requests q on q.id = p.quote_id;

update public.quote_variants v
   set accepted_at = q.updated_at
  from public.quote_proposals p
  join public.quote_requests q on q.id = p.quote_id
 where v.proposal_id = p.id and p.status = 'published' and q.status = 'accepted';

