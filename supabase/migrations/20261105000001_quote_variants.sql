-- ---------------------------------------------------------------- team
-- Opens the quote's draft. A new round starts as a copy of the options last sent.
create or replace function public.quote_start_draft(p_quote_id bigint)
returns bigint language plpgsql security definer set search_path = public as $$
declare
  v_quote public.quote_requests;
  v_last public.quote_proposals;
  v_old public.quote_variants;
  v_new bigint;
  v_id bigint;
begin
  if not public.is_staff() then raise exception 'staff only' using errcode = '42501'; end if;
  select * into v_quote from public.quote_requests where id = p_quote_id for update;
  if not found then raise exception 'that quote does not exist' using errcode = 'P0001'; end if;
  if v_quote.status in ('accepted', 'cancelled') then
    raise exception 'this quote is closed' using errcode = 'P0001';
  end if;

  select id into v_id from public.quote_proposals where quote_id = p_quote_id and status = 'draft';
  if found then return v_id; end if;

  select * into v_last from public.quote_proposals where quote_id = p_quote_id order by version desc limit 1;
  insert into public.quote_proposals (quote_id, version)
  values (p_quote_id, coalesce(v_last.version, 0) + 1)
  returning id into v_id;

  if v_last.id is null then
    insert into public.quote_variants (proposal_id, start_date, end_date)
    values (v_id, v_quote.start_date, v_quote.end_date);
    return v_id;
  end if;

  for v_old in select * from public.quote_variants where proposal_id = v_last.id order by position, id loop
    insert into public.quote_variants (proposal_id, position, title, start_date, end_date, summary, total_price, commission_rate, valid_until)
    values (v_id, v_old.position, v_old.title, v_old.start_date, v_old.end_date, v_old.summary, v_old.total_price, v_old.commission_rate, v_old.valid_until)
    returning id into v_new;
    insert into public.quote_variant_files (variant_id, position, path, name, content_type, size_bytes)
    select v_new, position, path, name, content_type, size_bytes from public.quote_variant_files where variant_id = v_old.id;
  end loop;
  return v_id;
end $$;

-- Saves the whole draft at once: what isn't in the list is removed.
create or replace function public.quote_save_draft(p_proposal_id bigint, p_variants jsonb)
returns void language plpgsql security definer set search_path = public as $$
declare
  v_entry jsonb;
  v_position int;
  v_id bigint;
  v_keep bigint[] := '{}';
begin
  if not public.is_staff() then raise exception 'staff only' using errcode = '42501'; end if;
  perform 1 from public.quote_proposals where id = p_proposal_id and status = 'draft' for update;
  if not found then raise exception 'that draft does not exist' using errcode = 'P0001'; end if;
  if jsonb_typeof(p_variants) <> 'array' or jsonb_array_length(p_variants) = 0 then
    raise exception 'keep at least one option' using errcode = 'P0001';
  end if;

  select coalesce(array_agg((e ->> 'id')::bigint), '{}') into v_keep
  from jsonb_array_elements(p_variants) e where e ->> 'id' is not null;
  delete from public.quote_variants where proposal_id = p_proposal_id and not (id = any (v_keep));

  for v_entry, v_position in select value, ordinality - 1 from jsonb_array_elements(p_variants) with ordinality loop
    v_id := null;
    if v_entry ->> 'id' is not null then
      update public.quote_variants set
        position = v_position,
        title = nullif(trim(v_entry ->> 'title'), ''),
        start_date = (v_entry ->> 'startDate')::date,
        end_date = (v_entry ->> 'endDate')::date,
        summary = nullif(trim(v_entry ->> 'summary'), ''),
        total_price = (v_entry ->> 'totalPrice')::numeric,
        commission_rate = (v_entry ->> 'commissionRate')::numeric,
        valid_until = (v_entry ->> 'validUntil')::date
      where id = (v_entry ->> 'id')::bigint and proposal_id = p_proposal_id
      returning id into v_id;
      if v_id is null then raise exception 'reload the page and try again' using errcode = 'P0001'; end if;
    else
      insert into public.quote_variants (proposal_id, position, title, start_date, end_date, summary, total_price, commission_rate, valid_until)
      values (
        p_proposal_id, v_position, nullif(trim(v_entry ->> 'title'), ''),
        (v_entry ->> 'startDate')::date, (v_entry ->> 'endDate')::date, nullif(trim(v_entry ->> 'summary'), ''),
        (v_entry ->> 'totalPrice')::numeric, (v_entry ->> 'commissionRate')::numeric, (v_entry ->> 'validUntil')::date
      )
      returning id into v_id;
    end if;

    delete from public.quote_variant_files where variant_id = v_id;
    insert into public.quote_variant_files (variant_id, position, path, name, content_type, size_bytes)
    select v_id, ordinality - 1, f.value ->> 'path', f.value ->> 'name', f.value ->> 'contentType', (f.value ->> 'sizeBytes')::bigint
    from jsonb_array_elements(coalesce(v_entry -> 'files', '[]'::jsonb)) with ordinality f;
  end loop;
end $$;

-- All the options travel together, and only once each of them is complete.
create or replace function public.quote_send_proposal(p_proposal_id bigint)
returns void language plpgsql security definer set search_path = public as $$
declare
  v_proposal public.quote_proposals;
  v_quote public.quote_requests;
  v_variant public.quote_variants;
  v_number int := 0;
begin
  if not public.is_staff() then raise exception 'staff only' using errcode = '42501'; end if;
  select * into v_proposal from public.quote_proposals where id = p_proposal_id and status = 'draft' for update;
  if not found then raise exception 'that draft does not exist' using errcode = 'P0001'; end if;
  select * into v_quote from public.quote_requests where id = v_proposal.quote_id for update;
  if v_quote.status in ('accepted', 'cancelled') then
    raise exception 'this quote is closed' using errcode = 'P0001';
  end if;

  for v_variant in select * from public.quote_variants where proposal_id = p_proposal_id order by position, id loop
    v_number := v_number + 1;
    if v_variant.title is null then
      raise exception 'option % needs a title', v_number using errcode = 'P0001';
    end if;
    if v_variant.start_date is null or v_variant.end_date is null then
      raise exception 'option % needs its dates', v_number using errcode = 'P0001';
    end if;
    if coalesce(v_variant.total_price, 0) <= 0 then
      raise exception 'option % needs a total price', v_number using errcode = 'P0001';
    end if;
    if v_variant.commission_rate is null then
      raise exception 'option % needs the agent commission', v_number using errcode = 'P0001';
    end if;
  end loop;
  if v_number = 0 then raise exception 'add at least one option' using errcode = 'P0001'; end if;

  update public.quote_proposals set status = 'superseded'
   where quote_id = v_proposal.quote_id and status = 'published';
  update public.quote_proposals set status = 'published', published_at = now() where id = p_proposal_id;
  update public.quote_requests set status = 'proposal_sent' where id = v_proposal.quote_id;

  insert into public.quote_messages (quote_id, sender_id, from_staff, kind, body)
  values (
    v_proposal.quote_id, auth.uid(), true, 'event',
    'TravelXM sent ' || case when v_number = 1 then '1 option' else v_number || ' options' end || ' (version ' || v_proposal.version || ').'
  );
  perform public.quote_notify_agent(
    v_quote.agent_id,
    'Your proposal is ready',
    public.quote_label(v_quote.destination, v_quote.id) || ': ' || case when v_number = 1 then '1 option' else v_number || ' options' end || ' to review.',
    v_quote.id
  );
end $$;

